const STORAGE_KEY = 'neatshot-lang';

function readStoredLang() {
  try {
    return localStorage.getItem(STORAGE_KEY);
  } catch {
    return null;
  }
}

function storeLang(lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Trình duyệt chặn storage (private mode...) -> bỏ qua
  }
}

/**
 * Khởi tạo bộ chuyển ngôn ngữ.
 * @param {HTMLElement} root
 * @param {{ onChange?: (lang: string) => void, beforeSwap?: () => void }} hooks
 */
export function initI18n(root, hooks = {}) {
  const $$ = (s) => Array.from(root.querySelectorAll(s));
  const nodes = $$('[data-i18n]');
  nodes.forEach((el) => {
    if (el.dataset.en == null) el.dataset.en = el.textContent;
  });

  const indicator = root.querySelector('#lang-ind');
  const buttons = $$('[data-lang-btn]');
  let current = null;
  let swapTl = null;

  const moveIndicator = (lang) => {
    if (indicator) indicator.style.transform = lang === 'vi' ? 'translateX(38px)' : 'translateX(0)';
  };

  const apply = (lang, save) => {
    current = lang;
    moveIndicator(lang);
    hooks.beforeSwap?.();
    nodes.forEach((el) => {
      const key = el.dataset.i18n;
      el.textContent = lang === 'vi' && VI[key] != null ? VI[key] : el.dataset.en;
    });
    document.documentElement.lang = lang;
    buttons.forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.langBtn === lang)));
    if (save) storeLang(lang);
    hooks.onChange?.(lang);
  };

  const switchTo = (lang) => {
    const gsap = window.gsap;
    const reduce = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
    moveIndicator(lang);
    if (!gsap || reduce) {
      apply(lang, true);
      return;
    }
    const vh = window.innerHeight;
    const visible = nodes.filter((el) => {
      const r = el.getBoundingClientRect();
      return r.bottom > 0 && r.top < vh && r.width > 0;
    });
    if (swapTl) swapTl.progress(1).kill();
    swapTl = gsap.timeline()
      .to(visible, { opacity: 0, y: -4, duration: .16, ease: 'power2.in', stagger: .004 })
      .add(() => apply(lang, true))
      .fromTo(visible, { opacity: 0, y: 5 }, { opacity: 1, y: 0, duration: .34, ease: 'power3.out', stagger: .008, clearProps: 'transform' });
  };

  let initial = readStoredLang();
  if (initial !== 'en' && initial !== 'vi') {
    initial = (navigator.language || '').toLowerCase().startsWith('vi') ? 'vi' : 'en';
  }
  apply(initial, false);

  buttons.forEach((b) => b.addEventListener('click', () => {
    if (b.dataset.langBtn !== current) switchTo(b.dataset.langBtn);
  }));

  return { get lang() { return current; } };
}
